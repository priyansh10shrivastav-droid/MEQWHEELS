const FLEET_VERSION_KEY = 'meq_official_fleet_loaded_v2';

export function seedInitialData(): void {
  // If version key is not set, flush old demo data and load official vehicle fleet
  if (!localStorage.getItem(FLEET_VERSION_KEY)) {
    localStorage.removeItem(STORAGE_KEYS.BOOKINGS);
    localStorage.removeItem(STORAGE_KEYS.PAYMENTS);
    localStorage.removeItem(STORAGE_KEYS.CUSTOMERS);
    localStorage.setItem(STORAGE_KEYS.BOOKINGS, JSON.stringify([]));
    localStorage.setItem(STORAGE_KEYS.PAYMENTS, JSON.stringify([]));
    localStorage.setItem(STORAGE_KEYS.CUSTOMERS, JSON.stringify([]));
    localStorage.setItem(STORAGE_KEYS.VEHICLES, JSON.stringify(MEQ_OFFICIAL_FLEET));
    localStorage.setItem(FLEET_VERSION_KEY, 'true');
    return;
  }

  // Fallback if vehicles ever gets empty
  if (!localStorage.getItem(STORAGE_KEYS.VEHICLES)) {
    localStorage.setItem(STORAGE_KEYS.VEHICLES, JSON.stringify(MEQ_OFFICIAL_FLEET));
  }
}
